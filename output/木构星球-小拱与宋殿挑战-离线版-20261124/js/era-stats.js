/** 把总数格式化成便于阅读的中文（万以上进位）。 */
export function formatTotal(value) {
  if (value >= 10000) return `${Math.round(value / 10000)} 万`;
  return String(value);
}

/** 取某朝代的分省条形用的最大数（用于算宽度比例）。 */
export function provinceMax(stat) {
  return Math.max(1, ...stat.provinces.map(([, n]) => n));
}
